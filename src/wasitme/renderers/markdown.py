"""
Markdown renderer for CI/CD job summaries and GitHub PR comments.
Owned by Suriya (Principal Full-Stack Engineer).
"""
from __future__ import annotations

from wasitme.models import DiffResult


def render_markdown(diff_result: DiffResult) -> str:
    """Produces clean, formatted Markdown representing the DiffResult."""
    lines = []

    broke_count = len(diff_result.broke_after)
    already_count = len(diff_result.already_broken)
    fixed_count = len(diff_result.fixed)

    # Header / Verdict
    if diff_result.verdict == "REGRESSION_DETECTED":
        lines.append("### 🔴 wasitme: REGRESSION DETECTED\n")
        lines.append(
            f"> **Failure:** Introduced **{broke_count}** new regression(s). Baseline had {already_count} pre-existing issues; {fixed_count} resolved.\n"
        )
    elif diff_result.verdict == "PREEXISTING_ISSUES_ONLY":
        lines.append("### 🟡 wasitme: CLEAN (Pre-existing Issues Only)\n")
        lines.append(
            f"> **Passed:** **0** regressions introduced. {already_count} pre-existing issue(s) detected; {fixed_count} resolved.\n"
        )
    else:
        lines.append("### 🟢 wasitme: CLEAN\n")
        lines.append(
            f"> **Success:** **0** regressions introduced. All systems healthy. {fixed_count} issue(s) resolved.\n"
        )

    lines.append(
        f"*Baseline:* `{diff_result.baseline_taken_at}` | *Current:* `{diff_result.current_taken_at}`\n"
    )

    # Regressions
    if broke_count > 0:
        lines.append(f"#### 🔴 Broke After Your Change ({broke_count})\n")
        lines.append("| Kind | Key | Severity | Details |")
        lines.append("|---|---|---|---|")
        for i in diff_result.broke_after:
            lines.append(f"| `{i.kind.value}` | `{i.key}` | **{i.severity.value.upper()}** | {i.detail} |")
        lines.append("")

    # Pre-existing
    if already_count > 0:
        lines.append(f"<details><summary><b>🟡 Already Broken ({already_count})</b></summary>\n")
        lines.append("| Kind | Key | Details |")
        lines.append("|---|---|---|")
        for i in diff_result.already_broken:
            lines.append(f"| `{i.kind.value}` | `{i.key}` | {i.detail} |")
        lines.append("</details>\n")

    # Fixed
    if fixed_count > 0:
        lines.append(f"#### 🟢 Fixed ({fixed_count})\n")
        for i in diff_result.fixed:
            lines.append(f"- **{i.kind.value}** (`{i.key}`): {i.detail}")
        lines.append("")

    lines.append("---")
    lines.append("*Generated by [wasitme](https://github.com/nithink/wasitme)*")
    return "\n".join(lines)
